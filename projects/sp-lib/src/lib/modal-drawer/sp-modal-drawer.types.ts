/**
 * SpModalSize
 * Defines preset width configurations for the SpModal dialog window.
 *
 * @version 1.0.0
 * @since 2.0.0
 * @author Alessio Giacché
 */
export type SpModalSize = 'sm' | 'md' | 'lg' | 'xl' | 'full';

/**
 * SpDrawerPlacement
 * Defines the edge from which the SpDrawer slides into the viewport.
 *
 * @version 1.0.0
 * @since 2.0.0
 * @author Alessio Giacché
 */
export type SpDrawerPlacement = 'left' | 'right' | 'top' | 'bottom';

/**
 * SpDrawerSize
 * Defines the cross-axis dimension preset of the SpDrawer panel.
 *
 * @version 1.0.0
 * @since 2.0.0
 * @author Alessio Giacché
 */
export type SpDrawerSize = 'sm' | 'md' | 'lg' | 'full';
