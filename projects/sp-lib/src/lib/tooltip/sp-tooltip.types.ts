/**
 * SpTooltipPosition
 * Supported visual positions for the tooltip relative to its host element.
 */
export type SpTooltipPosition = 'top' | 'bottom' | 'left' | 'right';

/**
 * SpTooltipTheme
 * Supported color themes for the tooltip appearance.
 */
export type SpTooltipTheme = 'dark' | 'light' | 'primary';
